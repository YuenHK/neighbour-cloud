const { test } = require('node:test')
const assert = require('node:assert/strict'), fs = require('node:fs')
const modulePromise = import('data:text/javascript;base64,' + fs.readFileSync('deploy/cloud/web/community-state.js').toString('base64'))
test('readiness never invents hardware or future functions', async () => {
  const { createCommunityState } = await modulePromise, model = createCommunityState()
  assert.equal(Object.keys(model.snapshot()).length, 9)
  model.connected(); model.module('robots', 'loaded'); model.module('services', 'loaded')
  model.checks({ interface:'ready',runtime:'ready',avatar:'ready',input:'ready' })
  assert.equal(model.snapshot().eleuthia.state, 'ready')
  assert.equal(model.snapshot().apollo.state, 'ready')
  assert.equal(model.snapshot().artemis.state, 'planned')
  for (const key of ['hephaestus', 'poseidon', 'demeter', 'aether']) assert.equal(model.snapshot()[key].state, 'offline')
})
test('repairing awaits evidence, and microphone failure keeps text functions available', async () => {
  const { createCommunityState } = await modulePromise, model = createCommunityState()
  model.repair('eleuthia', 'retrying')
  assert.equal(model.snapshot().hades.state, 'repairing')
  model.checks({ interface:'ready',runtime:'ready',avatar:'ready',input:'ready' })
  assert.equal(model.snapshot().eleuthia.state, 'repairing')
  model.repair('eleuthia', 'retried')
  assert.equal(model.snapshot().eleuthia.state, 'loading')
  model.checks({ input:'ready' }); assert.equal(model.snapshot().eleuthia.state, 'ready')
  model.checks({ input:'action' }); assert.equal(model.snapshot().eleuthia.state, 'error')
  assert.equal(model.snapshot().apollo.state, 'ready')
})
test('failure remains isolated and a new launch clears stale evidence', async () => {
  const { createCommunityState } = await modulePromise, model = createCommunityState()
  model.module('robots', 'repairing'); model.module('robots', 'loaded')
  assert.equal(model.snapshot().hephaestus.state, 'offline')
  model.repair('minerva', 'retrying'); model.fail('minerva')
  assert.equal(model.snapshot().minerva.state, 'error')
  assert.equal(model.snapshot().hades.state, 'error')
  model.reset(); assert.equal(model.snapshot().minerva.state, 'loading')
  const detached = model.snapshot(); detached.artemis.state='ready'
  assert.equal(model.snapshot().artemis.state, 'planned')
})
test('cold boot never infers nine healthy components from one ready HTTP response', async () => {
  const { createCommunityState } = await modulePromise, model = createCommunityState()
  model.boot({rollout_waiting:true}); assert.equal(model.snapshot().hades.state, 'loading')
  model.boot({rollout_failed:true}); assert.equal(model.snapshot().hades.state, 'error')
  model.boot({public_ready:true}); assert.equal(model.snapshot().minerva.state, 'ready')
  assert.equal(model.snapshot().eleuthia.state, 'loading')
  assert.equal(model.snapshot().artemis.state, 'planned')
})
