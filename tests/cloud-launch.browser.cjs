// Fresh synthetic origin; no production, microphone, playback, model or EP calls.
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path')
const {chromium}=require(path.resolve('.experiments/optimization-lab-20261029/node/node_modules/playwright'))
const origin='https://launch.neighbour.test',area=path.resolve('.runtime/wide-readiness-gallery-20261102/launch')
async function main(){
 fs.mkdirSync(area,{recursive:true})
 const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',args:['--mute-audio']})
 const context=await browser.newContext({serviceWorkers:'block',permissions:[],viewport:{width:1280,height:900}})
 const errors=[],unexpected=[]
 await context.route('**/*',r=>{
  const u=new URL(r.request().url());if(u.origin!==origin){unexpected.push(u.href);return r.abort()}
  if(u.pathname==='/')return r.fulfill({contentType:'text/html',body:fs.readFileSync('deploy/cloud/web/index.html','utf8').replace('<script type="module" src="/cloud/shell.js"></script>','<script type="module" src="/harness.js"></script>')})
  if(u.pathname==='/harness.js')return r.fulfill({contentType:'text/javascript',body:`import {createLaunchScreen} from '/cloud/launch-screen.js';window.launch=createLaunchScreen(document,{onRetry(){window.retry=true},onContinue(){window.continued=true}});launch.start('resident');`})
  if(['/cloud/shell.css','/cloud/launch-screen.css','/cloud/launch-screen.js','/cloud/mascot.css','/cloud/community-systems.js','/cloud/community-products.js','/cloud/community-state.js','/cloud/community-systems.css','/cloud/community-introduction.css'].includes(u.pathname))return r.fulfill({contentType:u.pathname.endsWith('.js')?'text/javascript':'text/css',body:fs.readFileSync('deploy/cloud/web/'+u.pathname.split('/').pop())})
  if(['/assets/brand/neighbour-house-apricot-v1.webp','/assets/brand/icon-192.png','/assets/brand/favicon-32.png','/assets/brand/apple-touch-icon-180.png'].includes(u.pathname))return r.fulfill({contentType:u.pathname.endsWith('.webp')?'image/webp':'image/png',body:fs.readFileSync('deploy/cloud/web/brand/'+u.pathname.split('/').pop())})
  unexpected.push(u.pathname);return r.abort()
 })
 // Advance only the long-wait deadline; elapsed time and phase updates remain real.
 await context.addInitScript(()=>{const old=window.setTimeout.bind(window);window.setTimeout=(fn,ms,...args)=>old(fn,ms>=20000?1600:ms,...args)})
 try{
  const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));await page.goto(origin)
  await page.locator('#launchScreen[data-phase=connect]').waitFor()
  assert.equal(await page.locator('#launchProgress').getAttribute('aria-valuenow'),'0')
  assert.equal(await page.locator('#launchStep').textContent(),'第 1 / 3 步')
  assert.ok((await page.locator('.community-core-mascot').evaluate(n=>getComputedStyle(n).animationName))!=='none')
  await page.screenshot({path:path.join(area,'launch-desktop-connect.png')})
  await page.waitForTimeout(1100)
  await page.evaluate(()=>launch.start('resident','interface'))
  assert.match(await page.locator('#launchElapsed').textContent(),/已等候 [1-9]/)
  assert.equal(await page.locator('[data-launch-step=connect] .launch-step-number').textContent(),'✓')
  assert.equal(await page.locator('[data-launch-step=interface]').getAttribute('aria-current'),'step')
  await page.evaluate(()=>launch.phase('avatar'))
  assert.equal(await page.locator('#launchComplete').textContent(),'已完成 2 / 3 個階段')
  await page.getByRole('button',{name:'重新連接',exact:true}).waitFor()
  assert.equal(await page.locator('#launchProgress').getAttribute('aria-valuenow'),'2')
  assert.equal(await page.locator('#launchContinue').isVisible(),false)
  await page.screenshot({path:path.join(area,'launch-desktop-avatar.png')})
  await page.setViewportSize({width:390,height:844})
  await page.screenshot({path:path.join(area,'launch-mobile.png')})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  const buttons=await page.locator('#launchRetry').boundingBox();assert.ok(buttons.x>=0&&buttons.x+buttons.width<=390)
  await page.evaluate(()=>launch.checks({textReady:true,checks:{interface:'ready',runtime:'ready',avatar:'ready',input:'action'}}))
  assert.match(await page.locator('#launchDetail').textContent(),/語音收音（需要處理）/)
  await page.getByRole('button',{name:'先用文字開始',exact:true}).click()
  assert.equal(await page.evaluate(()=>continued),true)
  await page.evaluate(()=>launch.fail('合成載入失敗'))
  assert.equal(await page.locator('[data-state=current] .launch-step-state').textContent(),'未能完成')
  await page.getByRole('button',{name:'重新連接',exact:true}).click()
  assert.equal(await page.evaluate(()=>retry),true)
  await page.evaluate(()=>launch.start('staff','interface'))
  assert.equal(await page.locator('#launchStep').textContent(),'第 2 / 2 步')
  assert.equal(await page.locator('[data-launch-step=avatar]').isVisible(),false)
  await page.emulateMedia({reducedMotion:'reduce'})
  assert.equal(await page.locator('.community-core-mascot').evaluate(n=>getComputedStyle(n).animationName),'none')
  await page.evaluate(()=>launch.hide())
  const stopped=await page.locator('#launchElapsed').textContent()
  await page.waitForTimeout(1200)
  assert.equal(await page.locator('#launchElapsed').textContent(),stopped)
  assert.equal(await page.locator('#launchScreen').isVisible(),false)
  assert.deepEqual(errors,[]);assert.deepEqual(unexpected,[])
  const proof={real_milestones_only:true,completed_checks_and_current_step:true,no_time_based_fake_progress:true,elapsed_time:true,slow_and_failure_recovery:true,staff_two_steps:true,mobile_fits:true,animated_svg:true,reduced_motion:true,hidden_timers_stopped:true,no_external_or_provider_requests:true,errors,unexpected}
  fs.writeFileSync(path.join(area,'UI-VERIFIED.json'),JSON.stringify(proof,null,2));console.log(JSON.stringify(proof))
 }finally{await context.close();await browser.close()}
}
main().catch(e=>{console.error(e);process.exitCode=1})
